"""Benchmark: slim every snapshot and write bench/RESULTS.md (+ results.json).

    python bench/run_bench.py                       # tiktoken o200k_base only
    ANTHROPIC_API_KEY=... python bench/run_bench.py --anthropic   # + count_tokens

Numbers are measured, never typed in: RESULTS.md is generated by this script.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

import yaml

from toolslim.loaders import load_json_file
from toolslim.pipeline import run_pipeline
from toolslim.rules import all_rules, select_rules
from toolslim.tokenizers import TiktokenCounter

BENCH = Path(__file__).parent


def pct(a: int, b: int) -> str:
    return f"{100.0 * a / b:.1f}%" if b else "-"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--anthropic", action="store_true", help="also measure with count_tokens")
    ap.add_argument("--model", default="claude-sonnet-5-5")
    args = ap.parse_args()

    cfg = yaml.safe_load((BENCH / "servers.yaml").read_text())
    order = [s["name"] for s in cfg["servers"]]
    snaps = {p.stem: p for p in (BENCH / "snapshots").glob("*.json")}
    names = [n for n in order if n in snaps] + sorted(set(snaps) - set(order))

    tik = TiktokenCounter("o200k_base")
    anth = None
    if args.anthropic:
        from toolslim.tokenizers.anthropic_counter import AnthropicCounter

        anth = AnthropicCounter(args.model)

    rules = select_rules()
    rows, totals = [], {"tools": 0, "before": 0, "after": 0, "a_before": 0, "a_after": 0}
    rule_totals = {r.id: 0 for r in rules}
    for name in names:
        tools = load_json_file(snaps[name])
        res = run_pipeline(tools, rules, tik)
        row = {"server": name, "tools": len(tools), "before": res.tokens_before,
               "after": res.tokens_after,
               "rules": {r.rule_id: r.saved for r in res.per_rule}}  # fmt: skip
        if anth is not None:
            row["a_before"] = anth.count_tools(tools)
            row["a_after"] = anth.count_tools(res.tools)
            totals["a_before"] += row["a_before"]
            totals["a_after"] += row["a_after"]
        for k in ("tools", "before", "after"):
            totals[k] += row[k]
        for rid, saved in row["rules"].items():
            rule_totals[rid] += saved
        rows.append(row)
        print(f"{name:24} {row['tools']:3} tools {row['before']:6} -> {row['after']:6} "
              f"({pct(row['before'] - row['after'], row['before'])})", file=sys.stderr)  # fmt: skip

    (BENCH / "results.json").write_text(json.dumps(
        {"date": str(date.today()), "tokenizer": tik.name,
         "anthropic_model": args.model if anth else None, "servers": rows,
         "totals": totals, "rule_totals": rule_totals}, indent=2) + "\n")  # fmt: skip

    lines = [
        "# Benchmark results",
        "",
        f"Generated by `bench/run_bench.py` on {date.today()} from the snapshots in "
        "`bench/snapshots/` (see `bench/servers.yaml`). Lossless rules only (default "
        "`toolslim slim`). Token counts are for tool definitions alone, serialised as "
        "compact JSON in each server's own wire shape.",
        "",
    ]
    head = "| server | tools | o200k before | o200k after | saved |"
    sep = "|---|---:|---:|---:|---:|"
    if anth:
        head += " Claude before | Claude after | saved |"
        sep += "---:|---:|---:|"
    lines += [head, sep]
    for r in rows:
        line = (f"| {r['server']} | {r['tools']} | {r['before']:,} | {r['after']:,} | "
                f"{pct(r['before'] - r['after'], r['before'])} |")  # fmt: skip
        if anth:
            line += (f" {r['a_before']:,} | {r['a_after']:,} | "
                     f"{pct(r['a_before'] - r['a_after'], r['a_before'])} |")  # fmt: skip
        lines.append(line)
    t = totals
    saved_all = pct(t["before"] - t["after"], t["before"])
    total_line = (
        f"| **all {len(rows)} servers** | **{t['tools']}** | **{t['before']:,}** | "
        f"**{t['after']:,}** | **{saved_all}** |"
    )
    if anth:
        total_line += (f" **{t['a_before']:,}** | **{t['a_after']:,}** | "
                       f"**{pct(t['a_before'] - t['a_after'], t['a_before'])}** |")  # fmt: skip
    lines.append(total_line)
    per_server = [100.0 * (r["before"] - r["after"]) / r["before"] for r in rows if r["before"]]
    per_server.sort()
    median = per_server[len(per_server) // 2] if per_server else 0.0
    lines += [
        "",
        f"Median per-server saving: **{median:.1f}%** (range {per_server[0]:.1f}% - "
        f"{per_server[-1]:.1f}%).",
        "",
        "## Savings per rule (o200k_base, all servers)",
        "",
        "| rule | tokens saved | % of all tool tokens |",
        "|---|---:|---:|",
    ]
    names_by_id = {r.id: r.name for r in all_rules()}
    for rid, saved in rule_totals.items():
        lines.append(f"| {rid} {names_by_id[rid]} | {saved:,} | {pct(saved, t['before'])} |")
    if not anth:
        lines += [
            "",
            "> Claude numbers (`count_tokens`) are not in this run. Re-run with "
            "`ANTHROPIC_API_KEY=... python bench/run_bench.py --anthropic` to add them; "
            "tiktoken is only an approximation for Claude.",
        ]
    (BENCH / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"total: {t['before']} -> {t['after']} ({pct(t['before'] - t['after'], t['before'])})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
